#!/usr/bin/env python
"""Build on-policy trajectory pools at every saved OPD checkpoint.

For each adjacent checkpoint pair (S_k -> S_{k+10}), the position pool is the
rollouts generated by S_k itself (thinking template, T=1.0, max 4096). The
pool is scored by S_k, S_{k+10}, and the teacher. This removes the off-policy
confound of using fixed base/teacher text for later checkpoints.

Outputs under <out-dir>:
  rollouts/<pool_tag>.jsonl
  npz/<pool_tag>__<model_tag>.npz
"""

import argparse
import json
import sys
import time
import types
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))

import opd_entropy_absorption_extract as ex  # noqa: E402

CKPT_ROOT = (
    "/root/autodl-tmp/OPSD_OnPolicyDistillation/outputs/"
    "Qwen3-1.7B-noeval-OPD-sample_reverse_kl-teacher-Qwen3-4B-Instruct-2507-lr1e-6-bs64-steps80"
)
BASE = "/root/autodl-tmp/models/models/Qwen3-1.7B"
TEACHER = "/root/autodl-tmp/models/models/Qwen3-4B-Instruct-2507"


def default_checkpoints():
    out = [f"step_000={BASE}"]
    for step in range(10, 81, 10):
        out.append(f"step_{step:03d}={CKPT_ROOT}/global_step_{step}/actor/huggingface")
    return out


def parse_args():
    p = argparse.ArgumentParser()
    p.add_argument("--checkpoints", nargs="+", default=default_checkpoints())
    p.add_argument("--teacher", default=TEACHER)
    p.add_argument(
        "--train-parquet",
        default="/root/autodl-tmp/models/datasets/grpo_processed/train_opd_5120.parquet",
    )
    p.add_argument("--n-prompts", type=int, default=32)
    p.add_argument("--seed", type=int, default=42)
    p.add_argument("--max-new-tokens", type=int, default=4096)
    p.add_argument("--temperature", type=float, default=1.0)
    p.add_argument("--top-p", type=float, default=1.0)
    p.add_argument("--top-k", type=int, default=-1)
    p.add_argument("--topk-save", type=int, default=128)
    p.add_argument("--chunk", type=int, default=512)
    p.add_argument("--limit-prompts", type=int, default=0)
    p.add_argument(
        "--out-dir", default=str(REPO_ROOT / "outputs/opd_step_pools_20261104")
    )
    return p.parse_args()


def step_of(tag):
    return int(tag.split("_")[-1])


def main():
    args = parse_args()
    out_dir = Path(args.out_dir)
    (out_dir / "rollouts").mkdir(parents=True, exist_ok=True)
    (out_dir / "npz").mkdir(parents=True, exist_ok=True)

    ckpts = dict(item.split("=", 1) for item in args.checkpoints)
    tags = sorted(ckpts, key=step_of)
    pairs = [(tags[i], tags[i + 1]) for i in range(len(tags) - 1)]
    pools = [prev for prev, _ in pairs]
    print(f"[plan] {len(tags)} models, {len(pairs)} pairs, {len(pools)} pools", flush=True)
    for prev, nxt in pairs:
        print(f"  pool {prev} -> score {prev}, {nxt}, teacher", flush=True)

    from transformers import AutoTokenizer

    tokenizer = AutoTokenizer.from_pretrained(ckpts[tags[0]])
    prompts = ex.load_prompts(
        args.train_parquet, args.n_prompts, args.seed, args.limit_prompts, tokenizer
    )
    print(f"[data] {len(prompts)} prompts", flush=True)

    # Stage 1: on-policy rollout pools.
    rollouts_by_pool = {}
    for pool_tag in pools:
        path = out_dir / "rollouts" / f"{pool_tag}.jsonl"
        if path.exists():
            with open(path) as f:
                rollouts = [json.loads(line) for line in f]
            print(f"[rollout] reuse {pool_tag}: {len(rollouts)} seqs", flush=True)
        else:
            t0 = time.time()
            pool_args = types.SimpleNamespace(
                rollout_model=ckpts[pool_tag],
                max_new_tokens=args.max_new_tokens,
                temperature=args.temperature,
                top_p=args.top_p,
                top_k=args.top_k,
            )
            rollouts = ex.stage_rollouts(pool_args, prompts, path)
            print(f"[rollout] {pool_tag} took {time.time() - t0:.0f}s", flush=True)
        rollouts_by_pool[pool_tag] = rollouts

    # Stage 2: which model must score which pool.
    needed = {}
    for prev, nxt in pairs:
        needed.setdefault(prev, set()).add(prev)
        needed.setdefault(nxt, set()).add(prev)
    score_order = [t for t in tags if t in needed]  # students first
    score_order.append("teacher")
    needed["teacher"] = set(pools)
    paths = dict(ckpts)
    paths["teacher"] = args.teacher

    for tag in score_order:
        model_path = paths[tag]
        for pool_tag in sorted(needed[tag], key=step_of):
            npz_path = out_dir / "npz" / f"{pool_tag}__{tag}.npz"
            if npz_path.exists():
                print(f"[skip] {pool_tag}__{tag}", flush=True)
                continue
            ex.score_model(
                f"{pool_tag}__{tag}",
                model_path,
                rollouts_by_pool[pool_tag],
                npz_path,
                args.topk_save,
                args.chunk,
                tokenizer,
            )
    print("[done]", flush=True)


if __name__ == "__main__":
    main()
