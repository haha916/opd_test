#!/usr/bin/env python
"""Analyze signed-entropy-gap vs absorption on per-step on-policy pools.

Each pool is generated by S_k; absorption is measured from S_k to S_{k+10} on
that same pool, with the teacher fixed. Reports how the signed-dh effect
evolves across training.
"""

import argparse
import json
import sys
from pathlib import Path

import numpy as np
from scipy.stats import spearmanr

sys.path.insert(0, str(Path(__file__).resolve().parent))
import opd_entropy_absorption_analyze as m  # noqa: E402


def step_of(tag):
    return int(tag.split("_")[-1])


def load_pair(npz_dir, pool):
    files = {p.stem.split("__")[1]: p for p in npz_dir.glob(f"{pool}__*.npz")}
    if pool not in files or "teacher" not in files:
        return None
    nxt = [t for t in files if t not in (pool, "teacher")]
    if len(nxt) != 1:
        return None
    nxt = nxt[0]
    return {
        "pool": pool,
        "next": nxt,
        "prev": np.load(files[pool]),
        "next_data": np.load(files[nxt]),
        "teacher": np.load(files["teacher"]),
    }


def analyze_pair(d, n_boot=2000):
    prev = d["prev"]
    nxt = d["next_data"]
    T = d["teacher"]
    prompt_idx = prev["prompt_index"]
    assert np.array_equal(prompt_idx, nxt["prompt_index"])
    assert np.array_equal(prompt_idx, T["prompt_index"])

    H_T = T["entropy"].astype(np.float64)
    H_prev = prev["entropy"].astype(np.float64)
    lpy_prev = prev["logp_y"].astype(np.float64)
    lpy_next = nxt["logp_y"].astype(np.float64)
    A_logp = lpy_next - lpy_prev
    dh = H_prev - H_T
    absdh = np.abs(dh)

    kl_prev, ret_prev = m.kl_intersection(
        prev["top_ids"], prev["top_logp"], T["top_ids"], T["top_logp"]
    )
    kl_next, ret_next = m.kl_intersection(
        nxt["top_ids"], nxt["top_logp"], T["top_ids"], T["top_logp"]
    )
    A_kl = kl_prev - kl_next

    prompts = np.unique(prompt_idx)
    sel = H_T > 0.3
    rows = m.signed_dh_rows(
        dh[sel],
        H_prev[sel],
        H_T[sel],
        A_kl[sel],
        kl_prev[sel],
        A_logp[sel],
        prompt_idx[sel],
        np.unique(prompt_idx[sel]),
        n_bins=5,
    )

    sp_dh, sp_abs = [], []
    for p in prompts:
        mask = (prompt_idx == p) & sel
        if mask.sum() < 20 or np.std(dh[mask]) == 0:
            continue
        sp_dh.append(
            spearmanr(dh[mask], A_kl[mask], nan_policy="omit").statistic
        )
        sp_abs.append(
            spearmanr(np.abs(dh[mask]), A_kl[mask], nan_policy="omit").statistic
        )
    sp_dh = np.array([x for x in sp_dh if np.isfinite(x)])
    sp_abs = np.array([x for x in sp_abs if np.isfinite(x)])
    sp_dh_mean, sp_dh_lo, sp_dh_hi = m.boot_ci(sp_dh, n_boot)
    sp_abs_mean, sp_abs_lo, sp_abs_hi = m.boot_ci(sp_abs, n_boot)

    return {
        "pool": d["pool"],
        "next": d["next"],
        "n_positions": int(len(dh)),
        "n_positions_ht_gt_03": int(sel.sum()),
        "frac_dh_positive": float((dh > 0).mean()),
        "frac_dh_positive_ht_gt_03": float((dh[sel] > 0).mean()),
        "frac_dh_gt_03": float((dh > 0.3).mean()),
        "frac_dh_gt_03_ht_gt_03": float((dh[sel] > 0.3).mean()),
        "mean_dh": float(dh.mean()),
        "frac_H_T_lt_001": float((H_T < 0.01).mean()),
        "mean_H_T": float(H_T.mean()),
        "mean_H_prev": float(H_prev.mean()),
        "mean_KL_prev": float(np.nanmean(kl_prev)),
        "mean_A_kl": float(np.nanmean(A_kl)),
        "rel_overall": float(np.nanmean(A_kl) / max(np.nanmean(kl_prev), 1e-9)),
        "mean_A_logp": float(np.nanmean(A_logp)),
        "retained_mass_prev": float(np.nanmean(ret_prev)),
        "retained_mass_next": float(np.nanmean(ret_next)),
        "spearman_signed_dh_Akl": [sp_dh_mean, sp_dh_lo, sp_dh_hi],
        "spearman_absdh_Akl": [sp_abs_mean, sp_abs_lo, sp_abs_hi],
        "signed_dh_quintiles_H_T_gt_03": rows,
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", required=True)
    ap.add_argument("--bootstrap", type=int, default=2000)
    args = ap.parse_args()

    root = Path(args.dir)
    npz_dir = root / "npz"
    pools = sorted(
        {p.stem.split("__")[0] for p in npz_dir.glob("*__*.npz")}, key=step_of
    )
    results = []
    for pool in pools:
        d = load_pair(npz_dir, pool)
        if d is None:
            print(f"[warn] incomplete pair for {pool}", flush=True)
            continue
        results.append(analyze_pair(d, args.bootstrap))
    results.sort(key=lambda r: step_of(r["pool"]))

    lines = [
        "# On-policy step pools: signed entropy gap vs absorption",
        "",
        "Each row uses the rollouts generated by the *previous* checkpoint "
        "(T=1.0, thinking template, max 4096); absorption is measured from that "
        "checkpoint to the next 10-step checkpoint on the same tokens. "
        "rel_all = mean(A_kl)/mean(KL_prev) over all positions; rel q0/q4 are "
        "on positions with H_T>0.3.",
        "",
        "| pool -> next | n_pos | frac dh>0 | frac dh>0.3 | mean dh | H_T | H_S | KL_prev | A_kl | rel_all | rel q0 (dh<0) | rel q4 (dh>0) | q4 dh |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for r in results:
        q = r["signed_dh_quintiles_H_T_gt_03"]
        lines.append(
            f"| {r['pool']} -> {r['next']} | {r['n_positions']} | "
            f"{r['frac_dh_positive']:.3f} | {r['frac_dh_gt_03']:.3f} | "
            f"{r['mean_dh']:+.3f} | {r['mean_H_T']:.3f} | "
            f"{r['mean_H_prev']:.3f} | {r['mean_KL_prev']:.3f} | "
            f"{r['mean_A_kl']:+.4f} | {r['rel_overall']:.3f} | "
            f"{q[0]['rel_reduction']:.3f} ({q[0]['A_kl']:+.4f}) | "
            f"{q[4]['rel_reduction']:.3f} ({q[4]['A_kl']:+.4f}) | "
            f"{q[4]['dh']:+.3f} |"
        )
    lines += ["", "## Signed-dh quintile detail (H_T > 0.3)", ""]
    for r in results:
        lines.append(f"### {r['pool']} -> {r['next']}  "
                     f"(Spearman signed dh: {r['spearman_signed_dh_Akl'][0]:+.3f}, "
                     f"|dh|: {r['spearman_absdh_Akl'][0]:+.3f})")
        lines.append("")
        for q in r["signed_dh_quintiles_H_T_gt_03"]:
            lines.append(
                f"- q{q['quintile']}: dh={q['dh']:+.3f}, H_S={q['H_S_prev']:.3f}, "
                f"H_T={q['H_T']:.3f}, KL_prev={q['KL_prev']:.3f}, "
                f"A_kl={q['A_kl']:+.4f} [{q['A_kl_ci'][0]:+.4f},{q['A_kl_ci'][1]:+.4f}], "
                f"rel={q['rel_reduction']:.3f}, A_logp={q['A_logp']:+.4f}"
            )
        lines.append("")

    report = "\n".join(lines) + "\n"
    (root / "report.md").write_text(report)
    with open(root / "summary.json", "w") as f:
        json.dump(results, f, indent=2)
    print(report)
    print(f"[done] wrote {root / 'report.md'}", flush=True)


if __name__ == "__main__":
    main()
